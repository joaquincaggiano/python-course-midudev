###
# 02 - types()
# Python tiene varios tipos de datos
# int, float, complex, str, bool, NoneType, list, tuple, dict, range, set...
###

print("int:")
print(10)
print(-5)
print(type(10), end="\n\n") # La función type() devuelve el tipo de dato de la variable

print("float:")
print(3.14)
print(type(3.14), end="\n\n")

print("complex:")
print(1j + 2)
print(type(1j + 2), end="\n\n")

print("string:")
print("Hello, World!")
print(type("123"))
print(type(""), end="\n\n")

print("bool:")
print(True)
print(False)
print(type(1 > 2))
print(type(True), end="\n\n")

print("NoneType:")
print(None)
print(type(None), end="\n\n")